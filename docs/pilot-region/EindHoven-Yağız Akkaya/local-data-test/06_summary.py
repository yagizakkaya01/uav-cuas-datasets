"""Combine all downloaded layers: a single overview map and a markdown report.

Output: results/eindhoven-data-map.png, results/data-test-report.md
Only open data is shown; no sensor-placement or vulnerability analysis of the
military site is produced (the repository is public).
"""
import json
import sys

import numpy as np

from common import LOG_FILE
from config import AOI_RD, DATA, RESULTS


def load_raster(name, step=8):
    import rasterio
    p = DATA / "ahn" / f"{name}_05m.tif"
    if not p.exists():
        return None, None
    with rasterio.open(p) as src:
        a = src.read(1, out_shape=(src.height // step, src.width // step)).astype("float32")
        nd = src.nodata
        b = src.bounds
    if nd is not None:
        a[a == nd] = np.nan
    a[a < -100] = np.nan
    return a, (b.left, b.right, b.bottom, b.top)


def hillshade(z, cell, az=315, alt=45):
    gy, gx = np.gradient(np.nan_to_num(z, nan=np.nanmean(z)), cell)
    slope = np.pi / 2 - np.arctan(np.hypot(gx, gy))
    aspect = np.arctan2(-gx, gy)
    a, al = np.radians(az), np.radians(alt)
    return np.sin(al) * np.sin(slope) + np.cos(al) * np.cos(slope) * np.cos(a - aspect)


def main():
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from pyproj import Transformer
    tr = Transformer.from_crs(4326, 28992, always_xy=True)

    fig, ax = plt.subplots(figsize=(12, 9), dpi=150)
    extras = {}

    dsm, ext = load_raster("dsm")
    dtm, _ = load_raster("dtm")
    if dsm is not None:
        ax.imshow(hillshade(dsm, 4.0), cmap="gray", extent=ext, alpha=0.9)
        if dtm is not None and dtm.shape == dsm.shape:
            ndsm = dsm - dtm
            v = ndsm[np.isfinite(ndsm)]
            extras["ndsm_above_2_5m_pct"] = round(100 * float((v > 2.5).mean()), 1)
            extras["ndsm_p99_m"] = round(float(np.percentile(v, 99)), 1)

    bpath = DATA / "3dbag" / "buildings.geojson"
    if bpath.exists():
        from matplotlib.collections import PolyCollection
        feats = [f for f in json.loads(bpath.read_text(encoding="utf-8"))["features"] if f["geometry"]]
        polys = [np.array(f["geometry"]["coordinates"][0])[:, :2] for f in feats]
        h = np.array([f["properties"].get("height_above_ground_m") or 0 for f in feats])
        pc = PolyCollection(polys, array=h, cmap="viridis", clim=(0, max(20, np.percentile(h, 99))),
                            edgecolor="none")
        ax.add_collection(pc)
        fig.colorbar(pc, ax=ax, shrink=0.6, label="3DBAG building height above ground (m)")

    opath = DATA / "osm" / "osm.geojson"
    if opath.exists():
        for f in json.loads(opath.read_text(encoding="utf-8"))["features"]:
            aw = f["properties"].get("aeroway")
            if aw in ("runway", "taxiway") and f["geometry"]["type"] == "LineString":
                xy = np.array([tr.transform(*c) for c in f["geometry"]["coordinates"]])
                ax.plot(xy[:, 0], xy[:, 1], color="red" if aw == "runway" else "orange",
                        lw=2.5 if aw == "runway" else 0.8)

    for p in (DATA / "nofly").glob("*.geojson") if (DATA / "nofly").exists() else []:
        for f in json.loads(p.read_text(encoding="utf-8"))["features"]:
            g = f.get("geometry") or {}
            rings = (g.get("coordinates") or []) if g.get("type") == "Polygon" else \
                [r for poly in g.get("coordinates", []) for r in poly] if g.get("type") == "MultiPolygon" else []
            for ring in rings[:1] if g.get("type") == "Polygon" else rings:
                xy = np.array([tr.transform(*c[:2]) for c in ring])
                ax.plot(xy[:, 0], xy[:, 1], color="magenta", lw=1, ls="--")

    spath = DATA / "opensky" / "live_states.json"
    if spath.exists():
        st = json.loads(spath.read_text(encoding="utf-8")).get("states") or []
        pts = [tr.transform(s[5], s[6]) for s in st if s[5] and s[6]]
        if pts:
            pts = np.array(pts)
            ax.scatter(pts[:, 0], pts[:, 1], marker="^", s=60, c="cyan", edgecolor="k", zorder=5)

    x0, y0, x1, y1 = AOI_RD
    ax.set_xlim(x0, x1)
    ax.set_ylim(y0, y1)
    ax.set_title("Eindhoven (EHEH) pilot region: AHN hillshade, 3DBAG buildings, OSM runway/taxiways,\n"
                 "no-fly zone edges if available (magenta), live OpenSky aircraft (cyan)", fontsize=10)
    ax.set_xlabel("RD New x (m)")
    ax.set_ylabel("RD New y (m)")
    fig.tight_layout()
    fig.savefig(RESULTS / "eindhoven-data-map.png")

    rows = json.loads(LOG_FILE.read_text(encoding="utf-8")) if LOG_FILE.exists() else []
    lines = ["# Eindhoven local data test: results", "",
             "Generated by `run_all.py` on the team laptop. Raw data is in `data/` (not committed).", "",
             "| Source | Result | Detail | Tested (UTC) |", "|---|:---:|---|---|"]
    for r in rows:
        lines.append(f"| {r['source']} | {'✅' if r['ok'] else '❌'} | {r['detail']} | {r['tested_utc']} |")
    if extras:
        lines += ["", "## Derived checks", ""]
        if "ndsm_above_2_5m_pct" in extras:
            lines.append(f"- Share of the AOI where the surface is more than 2.5 m above the terrain "
                         f"(buildings, trees): **{extras['ndsm_above_2_5m_pct']} %**; 99th percentile object "
                         f"height {extras['ndsm_p99_m']} m. This is the obstruction layer for line-of-sight.")
    lines += ["", "![Overview map](eindhoven-data-map.png)", ""]
    if (DATA / "nofly" / "runway_buffer_fallback.geojson").exists():
        lines += ["*Magenta dashed line = FALLBACK zone: a buffer around the runway centreline "
                  "(modelling assumption, not an official zone).*", ""]
    if (RESULTS / "eindhoven-adsb-incident-night.png").exists():
        lines += ["![ADS-B traffic on the incident evening vs. a reference evening]"
                  "(eindhoven-adsb-incident-night.png)", ""]
    (RESULTS / "data-test-report.md").write_text("\n".join(lines), encoding="utf-8")
    print("wrote results/eindhoven-data-map.png and results/data-test-report.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
